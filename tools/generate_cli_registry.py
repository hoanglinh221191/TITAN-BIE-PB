#!/usr/bin/env python3
"""Generate TITAN's compile-time CLI option registry from parser wiring."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import tempfile


OPTION_NAME = r"(?:[A-Za-z][A-Za-z0-9_-]*|1pdb)"
OPTION_LITERAL = re.compile(rf'"(?P<option>--?{OPTION_NAME}=?)"')
SUBJECT = r'(?:\barg|\bcurrent_arg|string\s*\(\s*argv\s*\[\s*i\s*\]\s*\))'
DIRECT_EQUAL = re.compile(
    SUBJECT + rf'\s*==\s*"(?P<option>--?{OPTION_NAME})"'
)
DIRECT_LOOKUP = re.compile(
    SUBJECT
    + rf'\.(?:find|rfind)\(\s*"(?P<option>--?{OPTION_NAME}=?)"'
)


def normalize_option(raw: str) -> str | None:
    option = raw[:-1] if raw.endswith("=") else raw
    if option.endswith("-"):
        return None
    return option


def initializer_options(source: str, helper_pattern: str) -> set[str]:
    call = re.compile(
        rf'(?:{helper_pattern})\s*\(\s*arg\s*,\s*\{{(?P<flags>.*?)\}}',
        re.DOTALL,
    )
    options: set[str] = set()
    for match in call.finditer(source):
        for literal in OPTION_LITERAL.finditer(match.group("flags")):
            option = normalize_option(literal.group("option"))
            if option is not None:
                options.add(option)
    return options


def direct_boolean_options(source: str) -> set[str]:
    options: set[str] = set()
    # Calls often contain nested expressions such as string(argv[i]).  Stop at
    # the statement terminator instead of the first closing parenthesis so the
    # final flag-name literal is retained (notably for the historical -1pdb
    # switch).
    calls = re.compile(
        r'parse_bool_equals\s*\((?P<body>[^;]{0,1200})\)\s*;', re.DOTALL
    )
    for call in calls.finditer(source):
        literals = list(OPTION_LITERAL.finditer(call.group("body")))
        if not literals:
            continue
        option = normalize_option(literals[-1].group("option"))
        if option is not None:
            options.add(option)
    return options


def extract_registry(source: str) -> tuple[list[str], list[str], list[str]]:
    value_options = initializer_options(
        source, r'consume_(?:(?:required_)?option_value|compound_option_value)'
    )
    boolean_options = initializer_options(source, r'consume_bool_option')
    boolean_options.update(direct_boolean_options(source))

    known_options = set(value_options)
    known_options.update(boolean_options)
    for match in DIRECT_EQUAL.finditer(source):
        option = normalize_option(match.group("option"))
        if option is not None:
            known_options.add(option)
            condition_tail = source[match.start() : match.start() + 600]
            condition_end = condition_tail.find("{")
            if condition_end >= 0:
                condition_tail = condition_tail[:condition_end]
            if re.search(r'i\s*\+\s*1\s*<\s*argc', condition_tail):
                value_options.add(option)
    for match in DIRECT_LOOKUP.finditer(source):
        raw = match.group("option")
        option = normalize_option(raw)
        if option is None:
            continue
        known_options.add(option)
        if raw.endswith("="):
            value_options.add(option)

    value_options.difference_update(boolean_options)
    required = {
        "-a",
        "-f",
        "--help",
        "--version",
        "-pbe-bie-opening-theta",
        "-pbctopo",
        "-sg",
    }
    missing = sorted(required - known_options)
    if missing:
        raise ValueError(f"registry extraction missed required options: {missing}")
    if len(known_options) < 500:
        raise ValueError(
            f"registry extraction found only {len(known_options)} options; parser scan is incomplete"
        )

    return (
        sorted(known_options),
        sorted(value_options),
        sorted(boolean_options),
    )


def render_array(name: str, values: list[str]) -> str:
    entries = "\n".join(f"    {json.dumps(value)}," for value in values)
    return (
        f"inline constexpr std::array<std::string_view, {len(values)}> {name} = {{\n"
        f"{entries}\n"
        "};\n"
    )


def render_header(source: str) -> str:
    known, valued, boolean = extract_registry(source)
    source_hash = hashlib.sha256(source.encode("utf-8")).hexdigest()
    return f"""// Generated by tools/generate_cli_registry.py. Do not edit.
#ifndef TITAN_CLI_REGISTRY_GENERATED_H
#define TITAN_CLI_REGISTRY_GENERATED_H

#include <array>
#include <string_view>

#define TITAN_CLI_REGISTRY_GENERATED 1

namespace titan_cli::generated {{

inline constexpr std::string_view parser_source_sha256 = "{source_hash}";

{render_array("known_options", known)}
{render_array("value_options", valued)}
{render_array("boolean_options", boolean)}
}} // namespace titan_cli::generated

#endif
"""


def write_if_changed(path: Path, content: str) -> bool:
    normalized = content.replace("\r\n", "\n")
    if path.exists() and path.read_text(encoding="utf-8") == normalized:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(
        mode="w",
        encoding="utf-8",
        newline="\n",
        dir=path.parent,
        prefix=f".{path.name}.",
        suffix=".tmp",
        delete=False,
    ) as handle:
        handle.write(normalized)
        temporary = Path(handle.name)
    os.replace(temporary, path)
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--parser", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    source = args.parser.read_text(encoding="utf-8-sig")
    content = render_header(source)
    if args.check:
        if not args.output.exists() or args.output.read_text(encoding="utf-8") != content:
            raise SystemExit(f"CLI registry is stale: {args.output}")
        return 0
    write_if_changed(args.output, content)
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, ValueError) as error:
        raise SystemExit(f"generate_cli_registry: {error}") from error
