int impl_write_pqr(fstream& output, const Multi_MOL& mol, size_t num_snap)
{
	size_t num{};
	for (size_t l{}; l < mol.m_mol[num_snap].size(); ++l)
	{
		l  > 99998 ? num = 99998 : num = l;
		string chain{ " " };
		if (!isdigit(mol.info[l].get_chain()[0]))chain = mol.info[l].get_chain();
		output << setw(4) << "ATOM" << setw(7) << num + 1  << setw(5) << mol.info[l].get_atom() << " "<< setw(4)<<left << mol.info[l].get_original_res_name()<<right << setw(1) << chain
			<< setw(4) << mol.info[l].get_resnr() << setw(12) << fixed << mol.m_mol[num_snap].pos.x[l] << setw(8) << fixed << mol.m_mol[num_snap].pos.y[l] << setw(8)
			<< mol.m_mol[num_snap].pos.z[l] << " " << setw(7) << static_cast<float>(mol.parameters[l].get_charge()) << " " << setw(6) << static_cast<float>(mol.parameters[l].get_radius()) << '\n';
	}
	output.close();
	return 0;
}

int write_pqr(const Multi_MOL& pro_in, const Multi_MOL& lig, vector<string>& input_line, int input_name, size_t num_snap, const arguments& Arguments,
	folders& paths)
{
	fstream pqr1;
	fstream pqr2;
	pqr1.precision(3);
	pqr2.precision(3);

	size_t posfile = input_name - Arguments.b_input;
	if (!input_line.empty())
	{
		string name_pqr{};
		if (Arguments.flag_separation_results == false)
		{
				fs::path p_temp = Arguments.pdb_name;
				name_pqr = p_temp.stem().string();
		}
		else
		{
			name_pqr = paths.path(posfile).stem().string();
		}

		if (pro_in.m_mol.empty())
			return 1;

		else if (pro_in.m_mol.size() > 1)
		{
			if (!lig.m_mol.empty())
				pqr1.open(paths.get_path(posfile)+ "/lg_" + name_pqr + to_string(num_snap) + ".pqr", ios::out);
			
			if (Arguments.flag_nocal == false)
				pqr2.open(paths.get_path(posfile) + "/rec_" + name_pqr + to_string(num_snap) + ".pqr", ios::out);
			else
				pqr2.open(paths.get_path(posfile) + "/" + name_pqr + to_string(num_snap) + ".pqr", ios::out);
		}
		else
		{
			if (!lig.m_mol.empty())
				pqr1.open(paths.get_path(posfile) + "/lg_" + name_pqr + ".pqr", ios::out);

			if (Arguments.flag_nocal == false)
				pqr2.open(paths.get_path(posfile) + "/rec_" + name_pqr + ".pqr", ios::out);
			else
				pqr2.open(paths.get_path(posfile) + "/" + name_pqr + ".pqr", ios::out);
		}
	}
	else
	{
		if (pro_in.m_mol.empty())
			return 1;
		else if (pro_in.m_mol.size() > 1)
		{
			if(!lig.m_mol.empty())
			pqr1.open("lg_" + to_string(posfile) + to_string(num_snap) + ".pqr", ios::out);

			pqr2.open("rec_" + to_string(posfile) + to_string(num_snap) + ".pqr", ios::out);
		}
		else
		{
			if (!lig.m_mol.empty())
			pqr1.open("lg_" + to_string(posfile) + ".pqr", ios::out);

			if (Arguments.flag_nocal == false)
				pqr2.open("rec_" + to_string(input_name) + ".pqr", ios::out);
			else
				pqr2.open(to_string(posfile) + ".pqr", ios::out);
		}
	}
	if (!pqr2.is_open()) cout << "Can not open .pqr file(s)!\n"; //cout << pro_in.m_mol.size();

	if (!lig.m_mol.empty())
	{
		impl_write_pqr(pqr1, lig, num_snap);
	}
	if (!pro_in.m_mol.empty())
	{
		impl_write_pqr(pqr2, pro_in, num_snap);
	}
	return 0;
}
int write_pdb(const Multi_MOL& pro_in, const Multi_MOL& lig, const arguments& Arguments, size_t num_snap, 
	folders& paths, vector<string>& input_line, int input_name)
{
	if (Arguments.opdb == false)
		return 1;
	else
	{
		fstream out_pdb;
		if (Arguments.flag_sep_opdb == true)
		{
			size_t posfile = input_name - Arguments.b_input;
			if (!input_line.empty())
			{
				out_pdb.open(paths.get_path(posfile) + "/" + Arguments.get_pdbOutput().substr(0, Arguments.get_pdbOutput().length()-4) 
					+"_" + to_string(num_snap) + ".pdb", ios::out);
			}
			else
			{
				out_pdb.open(Arguments.get_pdbOutput().substr(0,Arguments.get_pdbOutput().length() - 4)
					+ "_" + to_string(num_snap) + ".pdb", ios::out);
			}
			
		}	
		else
			out_pdb.open(Arguments.get_pdbOutput(), ios::out | ios::app);
		
		out_pdb.precision(3);
		out_pdb << "REMARK    GENERATED BY UNIVERSAL CALCULATOR\n";
		out_pdb << "TITLE     frame t= " << setw(9) << fixed << pro_in.m_mol[num_snap].time_of_snap << '\n'
			<< "REMARK    THIS IS SIMULATION BOX\n";
		out_pdb << "CRYST1" << setw(9) << fixed << pro_in.m_mol[num_snap].Box.get_a() << setw(9) << fixed << pro_in.m_mol[num_snap].Box.get_b()
			<< setw(9) << fixed << pro_in.m_mol[num_snap].Box.get_c() << setw(7) << pro_in.m_mol[num_snap].Box.get_alpha()
			<< setw(7) << pro_in.m_mol[num_snap].Box.get_beta() << setw(7) << pro_in.m_mol[num_snap].Box.get_gamma() << '\n';
		out_pdb << "MODEL" << setw(9) << num_snap + 1 << '\n';

		size_t num{};
		for (size_t k{}; k < pro_in.m_mol[num_snap].size(); ++k)
		{
			k <= 99998 ? num = k : num = 99998;
			out_pdb << setw(4) << "ATOM" << setw(7) << num + 1 << setw(5) << pro_in.info[k].get_atom()<< right << setw(5) << pro_in.info[k].get_original_res_name() << setw(1) << pro_in.info[k].get_chain() << setw(4) << pro_in.info[k].get_resnr() << setw(12)  << pro_in.m_mol[num_snap].pos.x[k] << setw(8) << pro_in.m_mol[num_snap].pos.y[k] << setw(8) << pro_in.m_mol[num_snap].pos.z[k] << " " << setw(7) << 1.00 << " " << setw(6) << 0.00 << '\n';
		}
		out_pdb << "TER\n";
		num = 0;
		
		if (Arguments.flag_nocal == false)
		{
			for (size_t k{}; k < lig.m_mol[num_snap].size(); ++k)
			{
				k + pro_in.m_mol[num_snap].size() <= 99998 ? num = k + pro_in.m_mol[num_snap].size() : num = 99998;
				out_pdb << setw(4) << "ATOM" << setw(7) << num + 1 << setw(5) << lig.info[k].get_atom() << setw(5) << right << lig.info[k].get_original_res_name() << setw(1) << lig.info[k].get_chain() << setw(4) << lig.info[k].get_resnr() << setw(12) << lig.m_mol[num_snap].pos.x[k] << setw(8) << lig.m_mol[num_snap].pos.y[k] << setw(8) << lig.m_mol[num_snap].pos.z[k] << " " << setw(7) << 1.00 << " " << setw(6) << 0.00 << '\n';
			}
			out_pdb << "TER\nENDMDL\n";
		}
		else
			out_pdb << "ENDMDL\n";
		out_pdb.close();
		return 0;
	}
}