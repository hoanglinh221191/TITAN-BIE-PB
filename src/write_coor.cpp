constexpr std::size_t kPdbOutputBufferSize = 1U << 20;
constexpr std::size_t kPdbFormatStackBufferSize = 256;

struct persistent_pdb_output {
	ofstream stream;
	string current_path{};
	array<char, kPdbOutputBufferSize> buffer{};

	void close()
	{
		if (stream.is_open())
		{
			stream.flush();
			stream.close();
		}
		stream.clear();
		current_path.clear();
	}

	bool open_append(const string& path)
	{
		if (!stream.is_open() || current_path != path)
		{
			close();
			stream.rdbuf()->pubsetbuf(buffer.data(),
				static_cast<std::streamsize>(buffer.size()));
			stream.open(path, ios::out | ios::app | ios::binary);
			current_path = path;
		}
		return stream.is_open();
	}

	bool write_append(const string& path, const string& data)
	{
		if (!open_append(path))
			return false;
		stream.write(data.data(), static_cast<std::streamsize>(data.size()));
		return stream.good();
	}
};

persistent_pdb_output& get_persistent_pdb_output()
{
	static persistent_pdb_output output;
	return output;
}

struct FastPdbBuffer {
	string data;

	void clear_and_reserve(size_t atom_count)
	{
		data.clear();
		const size_t target = 256 + atom_count * 96;
		if (data.capacity() < target)
			data.reserve(target);
	}

	void append(const char* text)
	{
		data.append(text);
	}
};

void append_format(FastPdbBuffer& buffer, const char* fmt, ...)
{
	char stack[kPdbFormatStackBufferSize];
	va_list args;
	va_start(args, fmt);
	const int needed = std::vsnprintf(stack, sizeof(stack), fmt, args);
	va_end(args);
	if (needed < 0)
		return;
	if (static_cast<size_t>(needed) < sizeof(stack))
	{
		buffer.data.append(stack, static_cast<size_t>(needed));
		return;
	}

	vector<char> dynamic_buffer(static_cast<size_t>(needed) + 1);
	va_start(args, fmt);
	std::vsnprintf(dynamic_buffer.data(), dynamic_buffer.size(), fmt, args);
	va_end(args);
	buffer.data.append(dynamic_buffer.data(), static_cast<size_t>(needed));
}

string pdb_chain_field(const mol_info& atom_info)
{
	const string chain = atom_info.get_chain();
	return chain.empty() ? string(" ") : chain;
}

void append_pdb_atom(FastPdbBuffer& buffer, size_t serial,
	const mol_info& atom_info, double x, double y, double z)
{
	const size_t clamped_serial = serial > 99999 ? 99999 : serial;
	const string atom = atom_info.get_atom();
	const string resname = atom_info.get_original_res_name();
	const string chain = pdb_chain_field(atom_info);
	append_format(buffer,
		"ATOM  %5zu %-4.4s %-4.4s%1.1s%4zu    %8.3f%8.3f%8.3f%6.2f%6.2f\n",
		clamped_serial, atom.c_str(), resname.c_str(), chain.c_str(),
		static_cast<size_t>(atom_info.get_resnr()), x, y, z, 1.00, 0.00);
}

void append_pdb_frame(FastPdbBuffer& buffer, const Multi_MOL& pro_in,
	const Multi_MOL& lig, size_t num_snap)
{
	const MOL& pro_frame = pro_in.m_mol[num_snap];
	const size_t pro_size = pro_frame.size();
	const bool write_lig =
		num_snap < lig.m_mol.size() && lig.m_mol[num_snap].size() != 0;
	const size_t lig_size = write_lig ? lig.m_mol[num_snap].size() : 0;

	buffer.clear_and_reserve(pro_size + lig_size);
	buffer.append("REMARK    GENERATED BY TITAN ENGINE\n");
	append_format(buffer, "TITLE     frame t= %9.3f\n",
		pro_frame.time_of_snap);
	buffer.append("REMARK    THIS IS SIMULATION BOX\n");
	append_format(buffer,
		"CRYST1%9.3f%9.3f%9.3f%7.3f%7.3f%7.3f\n",
		pro_frame.Box.get_a(), pro_frame.Box.get_b(), pro_frame.Box.get_c(),
		pro_frame.Box.get_alpha(), pro_frame.Box.get_beta(),
		pro_frame.Box.get_gamma());
	append_format(buffer, "MODEL%9zu\n", num_snap + 1);

	for (size_t k{}; k < pro_size; ++k)
	{
		append_pdb_atom(buffer, k + 1, pro_in.info[k], pro_frame.pos.x[k],
			pro_frame.pos.y[k], pro_frame.pos.z[k]);
	}
	buffer.append("TER\n");

	if (write_lig)
	{
		const MOL& lig_frame = lig.m_mol[num_snap];
		for (size_t k{}; k < lig_size; ++k)
		{
			append_pdb_atom(buffer, pro_size + k + 1, lig.info[k],
				lig_frame.pos.x[k], lig_frame.pos.y[k], lig_frame.pos.z[k]);
		}
		buffer.append("TER\nENDMDL\n");
	}
	else
	{
		buffer.append("ENDMDL\n");
	}
}

bool write_buffer_to_file(const string& path, const string& data)
{
	ofstream out(path, ios::out | ios::binary);
	if (!out.is_open())
		return false;
	out.write(data.data(), static_cast<std::streamsize>(data.size()));
	return out.good();
}

