bool patch_ray_full_padded_bound_for_audit(const PatchComplex &complex,
                                           PatchKind kind,
                                           std::size_t patch_index,
                                           double grid_spacing,
                                           PatchBounds &bounds) noexcept {
  bounds = {};
  return row_worklist_bounds_impl(complex, kind, patch_index, grid_spacing,
                                  bounds);
}

std::size_t PatchRayAxisRowWorklist::row_count() const noexcept {
  std::size_t result = 0U;
  return checked_multiply(u_count, v_count, result)
             ? result
             : std::numeric_limits<std::size_t>::max();
}

std::span<const PatchRefId>
PatchRayAxisRowWorklist::row(std::size_t row_index) const noexcept {
  if (row_index >= row_count() || row_index + 1U >= offsets.size())
    return {};
  const std::size_t begin = offsets[row_index];
  const std::size_t end = offsets[row_index + 1U];
  if (begin > end || end > candidates.size() || begin == end)
    return {};
  return {candidates.data() + begin, end - begin};
}

PreparedPatchRayRowWorklist build_patch_ray_row_worklist(
    const PatchComplex &complex, const PatchMappingGridSpec &spec,
    TitanExecutor *executor, PatchRayRowWorklistBuildOptions options) {
  using Clock = std::chrono::steady_clock;
  const auto started = Clock::now();
  PreparedPatchRayRowWorklist result;
  const auto elapsed = [&]() {
    return std::chrono::duration<double, std::milli>(Clock::now() - started)
        .count();
  };
  const auto fail = [&](std::string_view status) {
    PreparedPatchRayRowWorklist failed;
    failed.status.assign(status);
    failed.build_ms = elapsed();
    return failed;
  };

  try {
    std::array<std::size_t, 3> row_counts{};
    if (complex.status != "pass" ||
        !validate_patch_mapping_grid_spec(spec, &row_counts, nullptr))
      return fail("invalid_input");
    result.complex_fingerprint = fingerprint_patch_complex(complex);
    result.lattice_identity = make_patch_ray_lattice_identity(
        spec.lower, spec.grid_spacing, spec.nx, spec.ny, spec.nz);
    if (!result.complex_fingerprint.valid)
      return fail("invalid_patch_geometry");
    if (!result.lattice_identity.valid)
      return fail("invalid_input");

    std::size_t patch_count = 0U;
    if (!checked_add(patch_count, complex.contacts.size()) ||
        !checked_add(patch_count, complex.tori.size()) ||
        !checked_add(patch_count, complex.reentrant.size()))
      return fail("count_overflow");
    if (patch_count == 0U)
      return fail("invalid_patches");
    std::size_t rectangle_count = 0U;
    if (!checked_multiply(patch_count, 3U, rectangle_count))
      return fail("count_overflow");
    std::vector<PatchRowRectangle> rectangles;
    rectangles.resize(rectangle_count);
    result.requested_workers = executor == nullptr ? 1U : executor->capacity();
    if (result.requested_workers == 0U)
      return fail("invalid_executor");
    std::vector<std::uint8_t> bounds_workers(result.requested_workers, 0U);

    const auto bounds_started = Clock::now();
    const auto populate_patch = [&](std::size_t linear_patch) {
      const auto [kind, patch_index] = patch_address(complex, linear_patch);
      PatchRefId ref;
      if (!PatchRefId::try_make(kind, patch_index, ref))
        throw WorklistBuildFailure{"invalid_ref"};
      PatchBounds bounds;
      if (!patch_ray_full_padded_bound_for_audit(complex, kind, patch_index,
                                                 spec.grid_spacing, bounds))
        throw WorklistBuildFailure{"invalid_patch_geometry"};
      for (std::size_t axis_index = 0U; axis_index < 3U; ++axis_index) {
        const RayAxis axis = static_cast<RayAxis>(axis_index);
        double lower_u = 0.0;
        double lower_v = 0.0;
        std::size_t u_count = 0U;
        std::size_t v_count = 0U;
        double bound_lower_u = 0.0;
        double bound_upper_u = 0.0;
        double bound_lower_v = 0.0;
        double bound_upper_v = 0.0;
        PatchRowRectangle rectangle;
        rectangle.ref = ref;
        rectangle.axis = axis;
        if (!axis_grid(spec, axis, lower_u, u_count, lower_v, v_count) ||
            !projected_bounds(bounds, axis, bound_lower_u, bound_upper_u,
                              bound_lower_v, bound_upper_v) ||
            !grid_index_range(lower_u, spec.grid_spacing, u_count,
                              bound_lower_u, bound_upper_u, rectangle.u) ||
            !grid_index_range(lower_v, spec.grid_spacing, v_count,
                              bound_lower_v, bound_upper_v, rectangle.v))
          throw WorklistBuildFailure{"invalid_patch_geometry"};
        rectangles[linear_patch * 3U + axis_index] = rectangle;
      }
    };
    if (executor != nullptr && executor->capacity() > 1U) {
      executor->parallel_for(
          patch_count, executor->capacity(), 1U,
          [&](std::size_t worker, std::size_t begin, std::size_t end) {
            if (worker >= bounds_workers.size())
              throw WorklistBuildFailure{"worker_range"};
            bounds_workers[worker] = 1U;
            for (std::size_t patch = begin; patch < end; ++patch)
              populate_patch(patch);
          });
    } else {
      bounds_workers[0] = 1U;
      for (std::size_t patch = 0U; patch < patch_count; ++patch)
        populate_patch(patch);
    }
    result.bounds_workers_used = static_cast<std::size_t>(std::count(
        bounds_workers.begin(), bounds_workers.end(), std::uint8_t{1U}));
    if (result.bounds_workers_used == 0U)
      throw WorklistBuildFailure{"worker_range"};
    result.bounds_ms =
        std::chrono::duration<double, std::milli>(Clock::now() - bounds_started)
            .count();

    std::array<std::vector<std::size_t>, 3> counts;
    for (std::size_t axis = 0U; axis < 3U; ++axis) {
      result.axes[axis].axis = static_cast<RayAxis>(axis);
      double lower_u = 0.0;
      double lower_v = 0.0;
      if (!axis_grid(spec, result.axes[axis].axis, lower_u,
                     result.axes[axis].u_count, lower_v,
                     result.axes[axis].v_count))
        throw std::length_error("axis_grid");
      counts[axis].assign(row_counts[axis], 0U);
      if (!checked_add(result.total_rows, row_counts[axis]))
        throw std::length_error("row_count");
    }
    std::size_t retained = 0U;
    std::size_t peak = 0U;
    if (!temporary_payload_bytes(rectangles, counts, bounds_workers, retained,
                                 peak))
      throw std::length_error("bytes");
    result.accounted_peak_temporary_bytes = peak;

    const auto count_started = Clock::now();
    const auto count_rectangle = [&](const PatchRowRectangle &rectangle) {
      const std::size_t axis = static_cast<std::size_t>(rectangle.axis);
      if (axis >= counts.size())
        throw WorklistBuildFailure{"count_overflow"};
      std::size_t rectangle_pairs = 0U;
      if (!checked_multiply(rectangle.u.end - rectangle.u.begin,
                            rectangle.v.end - rectangle.v.begin,
                            rectangle_pairs) ||
          !checked_add(result.candidate_pairs, rectangle_pairs))
        throw WorklistBuildFailure{"count_overflow"};
      if (result.candidate_pairs > options.candidate_pair_limit)
        throw WorklistBuildFailure{"candidate_limit"};
      const std::size_t u_count = result.axes[axis].u_count;
      for (std::size_t v = rectangle.v.begin; v < rectangle.v.end; ++v) {
        for (std::size_t u = rectangle.u.begin; u < rectangle.u.end; ++u) {
          std::size_t row = 0U;
          if (!checked_multiply(v, u_count, row) || !checked_add(row, u) ||
              row >= counts[axis].size() || !checked_add(counts[axis][row], 1U))
            throw WorklistBuildFailure{"count_overflow"};
        }
      }
    };
    if (options.reverse_count_schedule_for_audit) {
      for (auto rectangle = rectangles.rbegin(); rectangle != rectangles.rend();
           ++rectangle)
        count_rectangle(*rectangle);
    } else {
      for (const PatchRowRectangle &rectangle : rectangles)
        count_rectangle(rectangle);
    }
    result.count_ms =
        std::chrono::duration<double, std::milli>(Clock::now() - count_started)
            .count();

    const auto prefix_started = Clock::now();
    std::size_t prefixed_pairs = 0U;
    for (std::size_t axis = 0U; axis < 3U; ++axis) {
      std::size_t sentinel = row_counts[axis];
      if (!checked_add(sentinel, 1U))
        throw WorklistBuildFailure{"count_overflow"};
      result.axes[axis].offsets.resize(sentinel, 0U);
      for (std::size_t row = 0U; row < row_counts[axis]; ++row) {
        const std::size_t occupancy = counts[axis][row];
        if (occupancy != 0U && !checked_add(result.nonempty_rows, 1U))
          throw WorklistBuildFailure{"count_overflow"};
        result.maximum_row_occupancy =
            std::max(result.maximum_row_occupancy, occupancy);
        if (!checked_add(prefixed_pairs, occupancy))
          throw WorklistBuildFailure{"count_overflow"};
        result.axes[axis].offsets[row + 1U] = prefixed_pairs;
      }
      result.axes[axis].candidates.resize(prefixed_pairs);
      for (std::size_t row = 0U; row < row_counts[axis]; ++row)
        counts[axis][row] = result.axes[axis].offsets[row];
      prefixed_pairs = 0U;
    }
    std::size_t allocated_pairs = 0U;
    for (const PatchRayAxisRowWorklist &axis : result.axes) {
      if (!checked_add(allocated_pairs, axis.candidates.size()))
        throw WorklistBuildFailure{"count_overflow"};
    }
    if (allocated_pairs != result.candidate_pairs ||
        !retained_payload_bytes(result, retained) ||
        !temporary_payload_bytes(rectangles, counts, bounds_workers, retained,
                                 peak))
      throw WorklistBuildFailure{"count_overflow"};
    result.accounted_peak_temporary_bytes =
        std::max(result.accounted_peak_temporary_bytes, peak);
    result.prefix_ms =
        std::chrono::duration<double, std::milli>(Clock::now() - prefix_started)
            .count();

    const auto fill_started = Clock::now();
    for (const PatchRowRectangle &rectangle : rectangles) {
      const std::size_t axis = static_cast<std::size_t>(rectangle.axis);
      const std::size_t u_count = result.axes[axis].u_count;
      for (std::size_t v = rectangle.v.begin; v < rectangle.v.end; ++v) {
        for (std::size_t u = rectangle.u.begin; u < rectangle.u.end; ++u) {
          std::size_t row = 0U;
          if (!checked_multiply(v, u_count, row) || !checked_add(row, u) ||
              row >= counts[axis].size())
            throw WorklistBuildFailure{"count_overflow"};
          const std::size_t position = counts[axis][row]++;
          if (position >= result.axes[axis].candidates.size())
            throw WorklistBuildFailure{"count_overflow"};
          result.axes[axis].candidates[position] = rectangle.ref;
        }
      }
    }
    for (std::size_t axis = 0U; axis < 3U; ++axis) {
      for (std::size_t row = 0U; row < row_counts[axis]; ++row) {
        if (counts[axis][row] != result.axes[axis].offsets[row + 1U])
          throw WorklistBuildFailure{"count_overflow"};
        const std::span<const PatchRefId> candidates =
            result.axes[axis].row(row);
        if (!std::is_sorted(candidates.begin(), candidates.end()) ||
            std::adjacent_find(candidates.begin(), candidates.end()) !=
                candidates.end())
          throw WorklistBuildFailure{"internal_order"};
      }
    }
    result.fill_ms =
        std::chrono::duration<double, std::milli>(Clock::now() - fill_started)
            .count();
    result.retained_bytes = retained;
    result.projected_aabb_worklist_complete = true;
    result.status = "pass";
    result.build_ms = elapsed();
    return result;
  } catch (const std::bad_alloc &) {
    return fail("alloc_fail");
  } catch (const WorklistBuildFailure &failure) {
    return fail(failure.status);
  } catch (const std::length_error &) {
    return fail("count_overflow");
  }
}

bool validate_patch_ray_row_worklist(
    const PatchComplex &complex, const PatchMappingGridSpec &spec,
    const PreparedPatchRayRowWorklist &prepared) noexcept {
  std::array<std::size_t, 3> row_counts{};
  const PatchComplexFingerprint fingerprint =
      fingerprint_patch_complex(complex);
  const PatchRayProvenance::LatticeIdentity lattice =
      make_patch_ray_lattice_identity(spec.lower, spec.grid_spacing, spec.nx,
                                      spec.ny, spec.nz);
  if (complex.status != "pass" ||
      !validate_patch_mapping_grid_spec(spec, &row_counts, nullptr) ||
      !fingerprint.valid || !lattice.valid ||
      prepared.complex_fingerprint != fingerprint ||
      prepared.lattice_identity != lattice || prepared.status != "pass" ||
      !prepared.projected_aabb_worklist_complete ||
      prepared.requested_workers == 0U || prepared.bounds_workers_used == 0U ||
      prepared.bounds_workers_used > prepared.requested_workers ||
      !std::isfinite(prepared.bounds_ms) || prepared.bounds_ms < 0.0 ||
      !std::isfinite(prepared.count_ms) || prepared.count_ms < 0.0 ||
      !std::isfinite(prepared.prefix_ms) || prepared.prefix_ms < 0.0 ||
      !std::isfinite(prepared.fill_ms) || prepared.fill_ms < 0.0 ||
      !std::isfinite(prepared.build_ms) || prepared.build_ms < 0.0)
    return false;

  std::size_t total_rows = 0U;
  std::size_t candidate_pairs = 0U;
  std::size_t nonempty_rows = 0U;
  std::size_t maximum_occupancy = 0U;
  for (std::size_t axis_index = 0U; axis_index < 3U; ++axis_index) {
    const PatchRayAxisRowWorklist &axis = prepared.axes[axis_index];
    double lower_u = 0.0;
    double lower_v = 0.0;
    std::size_t expected_u = 0U;
    std::size_t expected_v = 0U;
    std::size_t sentinel = row_counts[axis_index];
    if (!axis_grid(spec, static_cast<RayAxis>(axis_index), lower_u, expected_u,
                   lower_v, expected_v) ||
        !checked_add(sentinel, 1U) ||
        axis.axis != static_cast<RayAxis>(axis_index) ||
        axis.u_count != expected_u || axis.v_count != expected_v ||
        axis.offsets.size() != sentinel || axis.offsets.empty() ||
        axis.offsets.front() != 0U ||
        axis.offsets.back() != axis.candidates.size() ||
        !checked_add(total_rows, row_counts[axis_index]) ||
        !checked_add(candidate_pairs, axis.candidates.size()))
      return false;
    for (std::size_t row = 0U; row < row_counts[axis_index]; ++row) {
      const std::size_t begin = axis.offsets[row];
      const std::size_t end = axis.offsets[row + 1U];
      if (begin > end || end > axis.candidates.size())
        return false;
      const std::size_t occupancy = end - begin;
      nonempty_rows += static_cast<std::size_t>(occupancy != 0U);
      maximum_occupancy = std::max(maximum_occupancy, occupancy);
      if (occupancy == 0U)
        continue;
      const std::span<const PatchRefId> candidates(
          axis.candidates.data() + begin, occupancy);
      if (!std::is_sorted(candidates.begin(), candidates.end()) ||
          std::adjacent_find(candidates.begin(), candidates.end()) !=
              candidates.end() ||
          std::any_of(candidates.begin(), candidates.end(),
                      [&](PatchRefId ref) {
                        return !patch_ref_in_range(complex, ref);
                      }))
        return false;
    }
  }
  std::size_t retained = 0U;
  return retained_payload_bytes(prepared, retained) &&
         total_rows == prepared.total_rows &&
         candidate_pairs == prepared.candidate_pairs &&
         nonempty_rows == prepared.nonempty_rows &&
         maximum_occupancy == prepared.maximum_row_occupancy &&
         retained == prepared.retained_bytes &&
         prepared.accounted_peak_temporary_bytes >= prepared.retained_bytes;
}

