#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
from pathlib import Path

import numpy as np


def read_lines(path: Path) -> list[str]:
    return path.read_text(encoding="utf-8", errors="ignore").splitlines()


def numeric_rows(path: Path) -> list[list[str]]:
    rows: list[list[str]] = []
    for raw in read_lines(path):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        rows.append(line.split())
    return rows


def load_tica(path: Path) -> np.ndarray:
    rows = numeric_rows(path)
    return np.array([[int(float(r[0])), float(r[1]), float(r[2])] for r in rows], dtype=float)


def load_macrostate_traj(path: Path) -> np.ndarray:
    rows = numeric_rows(path)
    return np.array([[int(float(r[0])), int(float(r[1])), int(float(r[2]))] for r in rows], dtype=int)


def load_pca(path: Path) -> np.ndarray:
    with path.open("r", encoding="utf-8", errors="ignore", newline="") as handle:
        reader = csv.DictReader(handle)
        rows = [(int(row["Frame"]), float(row["PC1"]), float(row["PC2"])) for row in reader]
    return np.array(rows, dtype=float)


def load_rmsd_times(path: Path) -> np.ndarray:
    rows = numeric_rows(path)
    return np.array([float(r[1]) for r in rows], dtype=float)


def walker_info(outdir: Path) -> tuple[list[int], list[np.ndarray]]:
    rmsd_files = sorted(outdir.glob("rmsd_*.dat"), key=lambda p: int(p.stem.split("_")[-1]))
    if not rmsd_files:
        raise FileNotFoundError("No rmsd_*.dat files found.")
    counts: list[int] = []
    times: list[np.ndarray] = []
    for path in rmsd_files:
        t = load_rmsd_times(path)
        times.append(t)
        counts.append(int(t.size))
    return counts, times


def global_to_local_map(counts: list[int]) -> list[tuple[int, int]]:
    mapping: list[tuple[int, int]] = []
    for walker, count in enumerate(counts):
        mapping.extend((walker, local) for local in range(count))
    return mapping


def macrostate_representatives(tica: np.ndarray, macro_traj: np.ndarray, mapping: list[tuple[int, int]], times_by_walker: list[np.ndarray]) -> list[dict[str, object]]:
    results: list[dict[str, object]] = []
    macro_ids = sorted(set(macro_traj[:, 2].tolist()))
    for macro_id in macro_ids:
        idx = np.where(macro_traj[:, 2] == macro_id)[0]
        pts = tica[idx, 1:3]
        centroid = pts.mean(axis=0)
        d2 = ((pts - centroid) ** 2).sum(axis=1)
        best_idx = idx[int(np.argmin(d2))]
        global_frame = int(tica[best_idx, 0])
        walker, local_frame = mapping[global_frame]
        time_ps = float(times_by_walker[walker][local_frame])
        results.append(
            {
                "label": f"TICA_M{macro_id}",
                "mode": "macrostate_centroid",
                "global_frame": global_frame,
                "walker": walker,
                "local_frame": local_frame,
                "time_ps": time_ps,
                "x": float(tica[best_idx, 1]),
                "y": float(tica[best_idx, 2]),
                "note": f"Nearest frame to TICA centroid of macrostate M{macro_id}",
            }
        )
    return results


def pca_extremes(pca: np.ndarray, mapping: list[tuple[int, int]], times_by_walker: list[np.ndarray]) -> list[dict[str, object]]:
    specs = [
        ("PCA_PC1_min", 1, np.argmin, "Minimum along PC1"),
        ("PCA_PC1_max", 1, np.argmax, "Maximum along PC1"),
        ("PCA_PC2_min", 2, np.argmin, "Minimum along PC2"),
        ("PCA_PC2_max", 2, np.argmax, "Maximum along PC2"),
    ]
    results: list[dict[str, object]] = []
    for label, col, func, note in specs:
        idx = int(func(pca[:, col]))
        global_frame = int(pca[idx, 0])
        walker, local_frame = mapping[global_frame]
        time_ps = float(times_by_walker[walker][local_frame])
        results.append(
            {
                "label": label,
                "mode": "pca_extreme",
                "global_frame": global_frame,
                "walker": walker,
                "local_frame": local_frame,
                "time_ps": time_ps,
                "x": float(pca[idx, 1]),
                "y": float(pca[idx, 2]),
                "note": note,
            }
        )
    return results


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    fieldnames = ["label", "mode", "global_frame", "walker", "local_frame", "time_ps", "x", "y", "note"]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_ps1(path: Path, rows: list[dict[str, object]], traj_pattern: str, structure: str, gmx_cmd: str) -> None:
    lines = [
        "# PowerShell helper generated by select_representative_frames.py",
        "# Edit the output group interactively when gmx trjconv prompts.",
        "",
    ]
    for row in rows:
        walker = int(row["walker"])
        traj = traj_pattern.format(walker=walker)
        out_name = f"{row['label']}_w{walker}_f{int(row['local_frame']):05d}.pdb"
        lines.append(f"# {row['note']}")
        lines.append(
            f"{gmx_cmd} trjconv -f \"{traj}\" -s \"{structure}\" -dump {row['time_ps']:.1f} -o \"{out_name}\""
        )
        lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Select representative frames from TITAN PCA/TICA outputs.")
    parser.add_argument("--outdir", required=True, help="TITAN output directory")
    parser.add_argument("--output-dir", default=".", help="Directory for generated CSV/PS1 helper files")
    parser.add_argument("--structure", default="md1_snap0.pdb", help="Structure file passed to gmx trjconv")
    parser.add_argument("--traj-pattern", default="{walker}/awh1.xtc", help="Trajectory pattern, e.g. {walker}/awh1.xtc")
    parser.add_argument("--gmx", default="gmx", help="GROMACS command name")
    parser.add_argument("--prefix", default="representative_frames", help="Output file prefix")
    args = parser.parse_args()

    outdir = Path(args.outdir).expanduser().resolve()
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    counts, times_by_walker = walker_info(outdir)
    mapping = global_to_local_map(counts)

    tica = load_tica(outdir / "tica_projections.csv")
    macro_traj = load_macrostate_traj(outdir / "msm_macrostate_traj.dat")
    pca = load_pca(outdir / "pca_fel.csv")

    rows = macrostate_representatives(tica, macro_traj, mapping, times_by_walker)
    rows.extend(pca_extremes(pca, mapping, times_by_walker))

    csv_path = output_dir / f"{args.prefix}.csv"
    ps1_path = output_dir / f"{args.prefix}_extract.ps1"
    write_csv(csv_path, rows)
    write_ps1(ps1_path, rows, args.traj_pattern, args.structure, args.gmx)

    print(f"Wrote {csv_path}")
    print(f"Wrote {ps1_path}")
    for row in rows:
        print(
            f"{row['label']}: walker={row['walker']} local_frame={row['local_frame']} "
            f"time_ps={row['time_ps']:.1f} note={row['note']}"
        )


if __name__ == "__main__":
    main()
